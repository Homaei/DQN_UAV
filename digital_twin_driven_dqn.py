# Experience replay buffer
# ═══════════════════════════════════════════════════════════════
class ReplayBuffer:
    """
    Circular buffer that stores past (state, action, reward) transitions.
    When full, oldest entries get overwritten.
    Sampling random batches breaks correlations in the training data.
    """
    def __init__(self, max_size: int = 100_000):
        self.storage  = []
        self.max_size = max_size
        self.ptr      = 0

    def add(self, s, s2, node, vel, reward):
        t = (s, s2, node, vel, reward)
        if len(self.storage) < self.max_size:
            self.storage.append(t)
        else:
            self.storage[self.ptr] = t
            self.ptr = (self.ptr + 1) % self.max_size

    def sample(self, batch_size: int):
        idx = np.random.randint(0, len(self.storage), size=batch_size)
        s, s2, n, v, r = zip(*[self.storage[i] for i in idx])
        return (
            torch.FloatTensor(np.array(s)),
            torch.FloatTensor(np.array(s2)),
            torch.LongTensor(np.array(n)),
            torch.LongTensor(np.array(v)),
            torch.FloatTensor(np.array(r)).unsqueeze(1),
        )

    def __len__(self):
        return len(self.storage)


# ═══════════════════════════════════════════════════════════════
# DQN agent
# ═══════════════════════════════════════════════════════════════
class Agent:
    """
    DQN agent with epsilon-greedy exploration and a target network.

    We keep two copies of the network:
      Q        ->  the online network that gets updated every step
      Q_target ->  a lagged copy used to compute stable training targets

    The target network is soft-updated toward Q each step (tau=0.005),
    which stabilises training compared to copying weights all at once.
    """
    def __init__(self, state_dim: int, num_nodes: int, num_velocities: int,
                 lr: float = 1e-3, gamma: float = 0.99, tau: float = 0.005):
        self.num_nodes      = num_nodes
        self.num_velocities = num_velocities
        self.gamma          = gamma
        self.tau            = tau

        self.Q        = MultiHeadDQN(state_dim, num_nodes, num_velocities)
        self.Q_target = MultiHeadDQN(state_dim, num_nodes, num_velocities)
        self.Q_target.load_state_dict(self.Q.state_dict())
        self.optimizer = optim.Adam(self.Q.parameters(), lr=lr)

    def select_action(self, state: np.ndarray, epsilon: float):
        """With probability epsilon pick randomly, otherwise pick the best action."""
        if random.random() < epsilon:
            return (random.randint(0, self.num_nodes - 1),
                    random.randint(0, self.num_velocities - 1))
        with torch.no_grad():
            s = torch.FloatTensor(state).unsqueeze(0)
            qn, qv = self.Q(s)
            return torch.argmax(qn).item(), torch.argmax(qv).item()

    def train_step(self, buf: ReplayBuffer, batch_size: int = 100):
        """One gradient update using a random batch from the replay buffer."""
        if len(buf) < batch_size:
            return None     # not enough data yet

        s, s2, n, v, r = buf.sample(batch_size)

        # Q-values for the actions that were actually taken
        qn, qv  = self.Q(s)
        q_n_cur = qn.gather(1, n.unsqueeze(1)).squeeze(1)
        q_v_cur = qv.gather(1, v.unsqueeze(1)).squeeze(1)

        # Bellman targets from the target network
        with torch.no_grad():
            qn2, qv2 = self.Q_target(s2)
            tgt_n    = r.squeeze() + self.gamma * qn2.max(1)[0]
            tgt_v    = r.squeeze() + self.gamma * qv2.max(1)[0]

        loss = nn.MSELoss()(q_n_cur, tgt_n) + nn.MSELoss()(q_v_cur, tgt_v)
        self.optimizer.zero_grad()
        loss.backward()
        self.optimizer.step()

        # soft update: nudge target network slightly toward online network
        for tp, p in zip(self.Q_target.parameters(), self.Q.parameters()):
            tp.data.copy_(self.tau * p.data + (1 - self.tau) * tp.data)

        return loss.item()

    def save(self, path: str = "dt_dqn.pth"):
        torch.save(self.Q.state_dict(), path)

    def load(self, path: str = "dt_dqn.pth"):
        self.Q.load_state_dict(torch.load(path, weights_only=True))
        self.Q_target.load_state_dict(self.Q.state_dict())



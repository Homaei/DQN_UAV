# Anomaly detector
# Watches for suspicious gaps between twin predictions and real readings
# ═══════════════════════════════════════════════════════════════
class FaultDetector:
    """
    Statistical test for anomalies in UAV telemetry.

    If the measured path-loss is way off from what the twin predicted,
    something unusual happened — likely one of:
      - GPS spoofing attack (UAV thinks it's somewhere else)
      - False Data Injection (FDI) into sensor readings
      - Hardware fault in a sensor

    Method: z-score on a sliding window of residuals.
    Raises a flag when |z| > threshold_sigma.
    """
    def __init__(self, window: int = 10, threshold_sigma: float = 3.0):
        self.residuals     = deque(maxlen=window)
        self.threshold     = threshold_sigma
        self.anomaly_flags: List[bool] = []

    def check(self, predicted_pl: float, measured_pl: float) -> bool:
        """Returns True if an anomaly is detected."""
        res = measured_pl - predicted_pl
        self.residuals.append(res)
        if len(self.residuals) < 3:
            self.anomaly_flags.append(False)
            return False
        mu    = float(np.mean(self.residuals))
        sigma = max(float(np.std(self.residuals)), 0.1)
        z     = abs((res - mu) / sigma)
        flag  = bool(z > self.threshold)
        self.anomaly_flags.append(flag)
        return flag



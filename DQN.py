# ═══════════════════════════════════════════════════════════════
# 1-D Kalman filter
# Used to clean up noisy position and path-loss measurements
# ═══════════════════════════════════════════════════════════════
class KalmanFilter1D:
    """
    Minimal Kalman filter for a single scalar quantity.

    Every time a new noisy reading arrives from the UAV, this filter
    blends the current estimate with the measurement based on how
    much we trust each one, and returns a cleaner estimate.

    x  ->  current estimate of the value
    P  ->  how uncertain we are about x (variance)
    Q  ->  how much the true value drifts each step (process noise)
    R  ->  how noisy the sensor is (measurement noise)
    """
    def __init__(self, process_var: float = 0.5, meas_var: float = 9.0,
                 init_val: float = 0.0):
        self.x = init_val    # initial guess
        self.P = 10.0        # start very uncertain
        self.Q = process_var
        self.R = meas_var

    def update(self, measurement: float) -> float:
        # predict: uncertainty grows a little each step
        self.P = self.P + self.Q
        # update: blend measurement into estimate using Kalman gain
        K = self.P / (self.P + self.R)
        self.x = self.x + K * (measurement - self.x)
        self.P = (1 - K) * self.P
        return self.x


# ═══════════════════════════════════════════════════════════════
# Digital Twin calibrator
# Estimates the path-loss exponent alpha online from real data
# ═══════════════════════════════════════════════════════════════
class DTCalibrator:
    """
    Recursive least-squares (RLS) estimator for the path-loss exponent.

    Simplified path-loss model:
        PL(d) = 20*log10(4*pi*d/lambda) + alpha * 10*log10(d)

    Alpha depends on the environment (terrain, obstacles, altitude).
    The twin starts with alpha=2.0 but the real value is 2.8.
    Each new measurement nudges alpha closer to the true value.

    forgetting  ->  older data matters less over time (lambda < 1)
    """
    def __init__(self, alpha_init: float = 2.0, forgetting: float = 0.98):
        self.alpha  = alpha_init   # current estimate of the path-loss exponent
        self.P_rls  = 100.0       # RLS variance, starts high (very uncertain)
        self.lam    = forgetting   # forgetting factor

    def update(self, distance_m: float, measured_loss_db: float) -> float:
        """Take one (distance, measured path-loss) pair and update alpha."""
        if distance_m < 1.0:
            return self.alpha

        d_log    = 10.0 * math.log10(distance_m)
        # free-space loss with no environment component
        fs_loss  = 20.0 * math.log10(max(4 * math.pi * distance_m / WAVELENGTH, 1e-9))
        # what alpha*d_log must explain
        residual = measured_loss_db - fs_loss

        phi         = d_log
        K_rls       = (self.P_rls * phi) / (self.lam + phi * self.P_rls * phi)
        error       = residual - phi * self.alpha
        self.alpha += K_rls * error
        self.P_rls  = (1.0 / self.lam) * (1.0 - K_rls * phi) * self.P_rls
        # keep alpha in a physically sensible range
        self.alpha  = float(np.clip(self.alpha, 1.5, 5.0))
        return self.alpha



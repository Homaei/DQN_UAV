class KalmanBank:
    def __init__(self, n, Q, R, x0):
        self.x = x0.astype(float).copy()
        self.P = np.full(n, 1.0)
        self.Q, self.R = Q, R

    def update(self, z):
        Pp = self.P + self.Q
        K = Pp / (Pp + self.R)
        self.x = self.x + K * (z - self.x)
        self.P = (1.0 - K) * Pp
        return self.x.copy()


class RLS2:
    # cascaded scalar RLS: stage 1 -> mu, stage 2 -> theta (mean-centred pairs)
    def __init__(self, cfg, enabled=True):
        self.cfg, self.enabled = cfg, enabled
        self.mu_hat = float(cfg.mu0)
        self.th_hat = float(cfg.theta0)
        self.P_mu = float(cfg.rls_P0)
        self.P_th = float(cfg.rls_P0)
        self.lam = cfg.rls_lambda

    def update(self, v_prev, v_next):
        if not self.enabled:
            return
        c, lam = self.cfg, self.lam
        for x_prev, x_next in zip(v_prev, v_next):
            k1 = self.P_mu / (lam + self.P_mu)
            self.mu_hat += k1 * (x_next - self.mu_hat)
            self.P_mu = (1.0 - k1) * self.P_mu / lam
            phi = x_prev - self.mu_hat
            y = x_next - self.mu_hat
            k2 = self.P_th * phi / (lam + phi * phi * self.P_th)
            self.th_hat += k2 * (y - phi * self.th_hat)
            self.P_th = (1.0 - k2 * phi) * self.P_th / lam
        self.th_hat = float(np.clip(self.th_hat, c.theta_clip_lo, c.theta_clip_hi))
        self.mu_hat = float(np.clip(self.mu_hat, c.mu_clip_lo, c.mu_clip_hi))

    @property
    def theta(self):
        return float(self.th_hat)

    @property
    def mu(self):
        return float(self.mu_hat)


class DigitalTwinEngine:
    def __init__(self, cfg, rng, calibrate=True):
        self.cfg, self.rng = cfg, rng
        self.kf = KalmanBank(cfg.n_comp, cfg.kf_Q, cfg.kf_R, np.full(cfg.n_comp, cfg.mu0))
        self.rls = RLS2(cfg, enabled=calibrate)
        self.prev_filtered = None
        self.theta_hist, self.mu_hist = [], []
        self._res_win = []
        self.anom_flags = 0
        self.anom_checked = 0
        self.sync_count = 0

    def ingest(self, burst):
        for meas in burst:
            pred = None
            if self.prev_filtered is not None:
                pred = (self.rls.theta * self.prev_filtered +
                        (1.0 - self.rls.theta) * self.rls.mu)
            filt = self.kf.update(meas)
            if pred is not None:
                self._anomaly(float(np.mean(meas - pred)))
                self.rls.update(self.prev_filtered, filt)
            self.prev_filtered = filt
        self.sync_count += 1
        self.theta_hist.append(self.rls.theta)
        self.mu_hist.append(self.rls.mu)

    def _anomaly(self, r):
        c = self.cfg
        self._res_win.append(r)
        if len(self._res_win) > c.anom_window:
            self._res_win.pop(0)
        if self.sync_count >= c.anom_burnin and len(self._res_win) >= 10:
            m = float(np.mean(self._res_win))
            s = float(np.std(self._res_win)) + 1e-8
            self.anom_checked += 1
            if abs(r - m) / s > c.anom_gamma:
                self.anom_flags += 1

    def simulate_neighbors(self, n_samples, burnin=40):
        c = self.cfg
        th, mu = self.rls.theta, self.rls.mu
        v = np.clip(self.rng.normal(mu, 1.0, (n_samples, c.n_comp)), c.v_min, c.v_max)
        for _ in range(burnin):
            w = self.rng.normal(0.0, c.sigma_w, v.shape)
            v = np.clip(th * v + (1.0 - th) * mu + w, c.v_min, c.v_max)
        return v


class Denoiser(nn.Module):
    def __init__(self, cfg):
        super().__init__()
        d = cfg.n_comp
        in_dim = d + cfg.vel_dims + cfg.temb_dim
        self.temb_dim = cfg.temb_dim
        self.net = nn.Sequential(
            nn.Linear(in_dim, cfg.ddpm_hidden), nn.SiLU(),
            nn.Linear(cfg.ddpm_hidden, cfg.ddpm_hidden), nn.SiLU(),
            nn.Linear(cfg.ddpm_hidden, d),
        )

    def forward(self, x, t_frac, ctx):
        half = self.temb_dim // 2
        freqs = torch.exp(torch.linspace(0.0, math.log(1000.0), half, device=x.device))
        ang = t_frac[:, None] * freqs[None, :]
        emb = torch.cat([torch.sin(ang), torch.cos(ang)], dim=1)
        return self.net(torch.cat([x, ctx, emb], dim=1))


class ConditionalDDPM:
    def __init__(self, cfg, device="cpu"):
        self.cfg, self.device = cfg, device
        self.model = Denoiser(cfg).to(device)
        self.opt = torch.optim.Adam(self.model.parameters(), lr=cfg.ddpm_lr)
        T = cfg.ddpm_T
        self.T = T
        self.beta = torch.linspace(cfg.beta_min, cfg.beta_max, T, device=device)
        self.alpha = 1.0 - self.beta
        self.abar = torch.cumprod(self.alpha, dim=0)

    @staticmethod
    def _norm(v):
        return (v - 8.0) / 7.0

    @staticmethod
    def _denorm(x):
        return x * 7.0 + 8.0

    def fit(self, data_v, ctx_v, epochs):
        x0 = torch.tensor(self._norm(data_v), dtype=torch.float32, device=self.device)
        ctx = torch.tensor(self._norm(ctx_v), dtype=torch.float32, device=self.device)
        n, bs = x0.shape[0], self.cfg.ddpm_bs
        self.model.train()
        loss = torch.tensor(0.0)
        for _ in range(epochs):
            perm = torch.randperm(n)
            for i in range(0, n, bs):
                idx = perm[i:i + bs]
                xb, cb = x0[idx], ctx[idx]
                t = torch.randint(0, self.T, (xb.shape[0],), device=self.device)
                eps = torch.randn_like(xb)
                ab = self.abar[t][:, None]
                xt = ab.sqrt() * xb + (1.0 - ab).sqrt() * eps
                pred = self.model(xt, t.float() / self.T, cb)
                loss = F.mse_loss(pred, eps)
                self.opt.zero_grad()
                loss.backward()
                self.opt.step()
        return float(loss.item())

    @torch.no_grad()
    def sample(self, ctx_vec, n):
        self.model.eval()
        d = self.cfg.n_comp
        ctx = torch.tensor(self._norm(ctx_vec), dtype=torch.float32,
                           device=self.device)[None, :].repeat(n, 1)
        x = torch.randn(n, d, device=self.device)
        for t in reversed(range(self.T)):
            tf = torch.full((n,), t / self.T, device=self.device)
            eps = self.model(x, tf, ctx)
            a, ab, b = self.alpha[t], self.abar[t], self.beta[t]
            ab_prev = self.abar[t - 1] if t > 0 else torch.tensor(1.0, device=self.device)
            x = (x - b / (1.0 - ab).sqrt() * eps) / a.sqrt()
            if t > 0:
                var = b * (1.0 - ab_prev) / (1.0 - ab)
                x = x + var.sqrt() * torch.randn_like(x)
        v = self._denorm(x.cpu().numpy())
        return np.clip(v, self.cfg.v_min, self.cfg.v_max)



# Main training and deployment pipeline
# ═══════════════════════════════════════════════════════════════
def run_dt_driven_pipeline(
    max_episodes:  int   = 500,
    max_timesteps: int   = 30,
    batch_size:    int   = 100,
    epsilon_start: float = 1.0,
    epsilon_min:   float = 0.01,
    epsilon_decay: float = 0.995,
    sync_interval: int   = 5,       # sync twin with physical UAV every N steps
    save_path:     str   = "dt_dqn.pth",
):
    """
    Four-phase pipeline:

    Phases 1 and 2 run together:
      - agent trains inside the digital twin
      - every sync_interval steps, the twin gets a telemetry packet from the physical UAV
      - each sync corrects alpha and nudges sensor position beliefs toward reality

    Phase 3:
      - trained policy runs on the PhysicalUAVStub
      - twin keeps syncing in the background
    """
    twin  = DigitalTwin(num_nodes=NUM_NODES)
    phys  = PhysicalUAVStub(num_nodes=NUM_NODES)
    agent = Agent(twin.state_dim, NUM_NODES, len(VELOCITY_TABLE))
    buf   = ReplayBuffer()

    epsilon      = epsilon_start
    episode_aoi  = []
    episode_loss = []
    alpha_trace  = []

    print("=" * 60)
    print("  Digital Twin-Driven DRL Pipeline")
    print(f"  episodes={max_episodes}  steps/ep={max_timesteps}")
    print(f"  true alpha={TRUE_PATH_LOSS_EXP}, twin starts at alpha=2.0")
    print("=" * 60)

    for ep in range(max_episodes):
        state       = twin.reset()
        ep_aoi      = 0.0
        ep_loss     = 0.0
        ep_loss_cnt = 0

        for t in range(max_timesteps):
            node, vel = agent.select_action(state, epsilon)

            # step inside the twin
            next_state, reward, _, info = twin.step(node, vel)
            buf.add(state, next_state, node, vel, reward)

            # pull physical telemetry and sync the twin
            if t % sync_interval == 0:
                tel = phys.get_telemetry()
                twin.synchronise(tel)

            loss = agent.train_step(buf, batch_size)
            ep_aoi += float(np.mean(info["aoi"]))
            if loss is not None:
                ep_loss     += loss
                ep_loss_cnt += 1
            state = next_state

        epsilon   = max(epsilon_min, epsilon * epsilon_decay)
        avg_aoi   = ep_aoi / max_timesteps
        avg_loss  = ep_loss / max(ep_loss_cnt, 1)
        episode_aoi.append(avg_aoi)
        episode_loss.append(avg_loss)
        alpha_trace.append(twin.calibrator.alpha)

        if (ep + 1) % 50 == 0:
            print(f"  ep {ep+1:4d}/{max_episodes} | "
                  f"avg AoI={avg_aoi:.3f} | "
                  f"loss={avg_loss:.5f} | "
                  f"alpha_hat={twin.calibrator.alpha:.3f} | "
                  f"eps={epsilon:.3f} | "
                  f"anomalies={twin.anomaly_count}")

    agent.save(save_path)
    print(f"\nmodel saved -> {save_path}")
    print(f"total sync ops : {twin.sync_count}")
    print(f"total anomalies: {twin.anomaly_count}")
    print(f"final alpha_hat={twin.calibrator.alpha:.3f}  (true={TRUE_PATH_LOSS_EXP})")

    # Phase 3: test on the physical UAV stub
    print("\n-- Phase 3: deploy on Physical UAV --")
    deploy_aoi = []
    state = twin.reset()
    for t in range(100):
        node, vel = agent.select_action(state, epsilon=0.0)
        tel       = phys.execute_action(node, vel)
        twin.synchronise(tel)
        state = twin._get_state(node)
        deploy_aoi.append(float(np.mean(tel["aoi"])))
    print(f"  deployment avg AoI = {np.mean(deploy_aoi):.3f}")

    return agent, episode_aoi, episode_loss, alpha_trace, deploy_aoi


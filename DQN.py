# Digital Twin — the heart of the system
# ═══════════════════════════════════════════════════════════════
class DigitalTwin:
    """
    The digital twin: a living virtual copy of the UAV and its environment.

    What makes it more than a plain simulator:
      (A) maintains a belief state fused from noisy telemetry via Kalman filters
      (B) calibrates its own path-loss model online as new data arrives
      (C) flags anomalies in telemetry (GPS spoofing, FDI attacks)
      (D) exposes a Gym-style interface so DRL can train inside it
      (E) accepts sync packets from the physical UAV and updates itself

    State vector (length = NUM_NODES + 3):
        [AoI_0 ... AoI_{N-1},  path_loss_to_selected_sensor,  uav_x,  uav_y]
    """

    def __init__(self, num_nodes: int = NUM_NODES, seed: int = 42):
        self.num_nodes = num_nodes
        self.state_dim = num_nodes + 3

        random.seed(seed)
        np.random.seed(seed)

        # twin's initial belief about sensor positions (may be off from truth)
        self._node_xy = self._place_nodes()

        # UAV trajectory model
        theta        = np.linspace(0, 2 * math.pi, 361)
        self._uav_x  = UAV_RADIUS * np.cos(theta)
        self._uav_y  = UAV_RADIUS * np.sin(theta)

        # Kalman-filtered position estimate
        self._est_x = self._uav_x[0]
        self._est_y = self._uav_y[0]
        self._kf_x  = KalmanFilter1D(process_var=1.0,
                                      meas_var=POSITION_NOISE_STD**2,
                                      init_val=self._uav_x[0])
        self._kf_y  = KalmanFilter1D(process_var=1.0,
                                      meas_var=POSITION_NOISE_STD**2,
                                      init_val=self._uav_y[0])
        # separate Kalman filter for each sensor's path-loss
        self._kf_pl = [
            KalmanFilter1D(process_var=0.5,
                           meas_var=MEASUREMENT_NOISE_STD**2,
                           init_val=-80.0)
            for _ in range(num_nodes)
        ]

        # path-loss calibrator (starts at alpha=2.0, real value is 2.8)
        self.calibrator    = DTCalibrator(alpha_init=2.0)
        self._alpha        = self.calibrator.alpha

        # anomaly detector
        self.fault_detector = FaultDetector(window=10, threshold_sigma=3.0)
        self.anomaly_count  = 0
        self.sync_count     = 0
        self.alpha_history  = [self._alpha]

        self.reset()

    def _place_nodes(self):
        """Twin's initial guess for sensor positions (different seed from physical UAV)."""
        xy = []
        for _ in range(self.num_nodes):
            r  = UAV_RADIUS * math.sqrt(random.random())
            th = random.uniform(0, 2 * math.pi)
            xy.append((r * math.cos(th), r * math.sin(th)))
        return xy

    # ── Gym interface ──────────────────────────────────────────────
    def reset(self):
        """Reset the twin's internal state for a new episode."""
        self._queues = [deque() for _ in range(self.num_nodes)]
        self._aoi    = np.full(self.num_nodes, MAX_AOI, dtype=np.float32)
        self._t      = 0
        for i in range(self.num_nodes):
            if random.random() < PKT_ARRIVAL_P:
                for _ in range(20):
                    self._queues[i].append(1)
        return self._get_state(selected_node=0)

    def step(self, node_idx: int, velocity_idx: int):
        """Take one simulation step inside the twin."""
        velocity  = VELOCITY_TABLE[velocity_idx]
        steps_fwd = max(1, int(velocity * TIMESTEP_DUR))
        self._t   = (self._t + steps_fwd) % len(self._uav_x)

        # pull UAV position from the circular trajectory
        self._est_x = self._uav_x[self._t]
        self._est_y = self._uav_y[self._t]

        pl = self._compute_pathloss_calibrated()
        self._serve_node(node_idx, pl)
        self._age_other_nodes(node_idx)

        reward = -float(np.mean(self._aoi))    # negative AoI = we want to minimise it
        info   = {
            "pathloss":      pl,
            "aoi":           self._aoi.copy(),
            "alpha":         self._alpha,
            "anomaly_count": self.anomaly_count,
        }
        return self._get_state(node_idx), reward, False, info

    # ── Bidirectional synchronisation ─────────────────────────────
    def synchronise(self, telemetry: dict):
        """
        Receive a telemetry packet from the physical UAV and update the twin.

        This is the core of what makes it a real digital twin.
        Every time the physical UAV sends data, we do six things:

        1. clean up the noisy GPS position with the Kalman filter
        2. clean up each sensor's noisy path-loss reading
        3. use those cleaned readings to refine our estimate of alpha (RLS)
        4. compare twin prediction vs measurement to catch anomalies
        5. softly blend the physical AoI readings into the twin's belief
        6. slowly correct the twin's belief about sensor positions
        """
        self.sync_count += 1

        # 1. filter noisy GPS position
        self._est_x = self._kf_x.update(telemetry["pos_x"])
        self._est_y = self._kf_y.update(telemetry["pos_y"])

        # 2. filter each sensor's path-loss reading
        pl_meas = telemetry["path_loss"]
        pl_est  = []
        for i in range(self.num_nodes):
            est = self._kf_pl[i].update(float(pl_meas[i]))
            pl_est.append(est)

        # 3. update alpha using the cleaned path-loss and estimated distances
        for i in range(self.num_nodes):
            nx, ny = self._node_xy[i]
            d = math.sqrt((self._est_x - nx)**2 +
                          (self._est_y - ny)**2 + BASE_ALTITUDE**2)
            self._alpha = self.calibrator.update(d, pl_est[i])
        self.alpha_history.append(self._alpha)

        # 4. check for anomalies: compare what twin expected vs what arrived
        pl_dt_pred = self._compute_pathloss_calibrated()
        for i in range(self.num_nodes):
            if self.fault_detector.check(pl_dt_pred[i], float(pl_meas[i])):
                self.anomaly_count += 1

        # 5. soft blend: 70% trust old twin belief, 30% trust physical reading
        self._aoi = 0.7 * self._aoi + 0.3 * telemetry["aoi"]

        # 6. nudge sensor position beliefs slowly toward reported values
        if "node_xy" in telemetry:
            for i, (nx, ny) in enumerate(telemetry["node_xy"]):
                ox, oy = self._node_xy[i]
                # move 10% toward the physical reading each sync
                self._node_xy[i] = (0.9 * ox + 0.1 * nx,
                                    0.9 * oy + 0.1 * ny)

    # ── Path-loss with the calibrated model ───────────────────────
    def _compute_pathloss_calibrated(self):
        """Compute path-loss to all sensors using the current alpha estimate."""
        pl = []
        for i in range(self.num_nodes):
            nx, ny = self._node_xy[i]
            d = math.sqrt((self._est_x - nx)**2 +
                          (self._est_y - ny)**2 + BASE_ALTITUDE**2)
            d = max(d, 1.0)
            loss = (20 * math.log10(max(4 * math.pi * d / WAVELENGTH, 1e-9))
                    + self._alpha * 10 * math.log10(d))
            pl.append(loss)
        return pl

    def _serve_node(self, node_idx: int, pathloss: list):
        """Collect a packet from the selected sensor and update its AoI."""
        if random.random() < PKT_ARRIVAL_P:
            self._queues[node_idx].append(1)
        if self._queues[node_idx]:
            self._queues[node_idx].popleft()
            if pathloss[node_idx] < PKT_LOSS_THRESH:
                # channel too weak — reception failed
                self._aoi[node_idx] = min(self._aoi[node_idx] + 1, MAX_AOI)
            else:
                # successful delivery — AoI resets to 1
                self._aoi[node_idx] = 1.0
        else:
            # queue was empty
            self._aoi[node_idx] = min(self._aoi[node_idx] + 1, MAX_AOI)
        while len(self._queues[node_idx]) > MAX_QUEUE_LEN:
            self._queues[node_idx].popleft()

    def _age_other_nodes(self, selected: int):
        """Sensors that weren't visited this step get one unit older."""
        for i in range(self.num_nodes):
            if i == selected:
                continue
            if random.random() < PKT_ARRIVAL_P:
                self._queues[i].append(1)
            self._aoi[i] = min(self._aoi[i] + 1, MAX_AOI)
            while len(self._queues[i]) > MAX_QUEUE_LEN:
                self._queues[i].popleft()

    def _get_state(self, selected_node: int):
        """Build the current state vector."""
        pl    = self._compute_pathloss_calibrated()
        state = np.zeros(self.state_dim, dtype=np.float32)
        state[:self.num_nodes]    = self._aoi
        state[self.num_nodes]     = pl[selected_node]
        state[self.num_nodes + 1] = self._est_x
        state[self.num_nodes + 2] = self._est_y
        return state


# ═══════════════════════════════════════════════════════════════
# Neural network with two output heads
# ═══════════════════════════════════════════════════════════════
class MultiHeadDQN(nn.Module):
    """
    Shared backbone that feeds into two separate heads:
      head_nodes  ->  Q-values over which sensor to visit
      head_vel    ->  Q-values over which speed to fly at

    Both decisions share the same internal representation,
    which makes learning more efficient than two separate networks.
    """
    def __init__(self, state_dim: int, num_nodes: int,
                 num_velocities: int, hidden: int = 256):
        super().__init__()
        self.shared = nn.Sequential(
            nn.Linear(state_dim, hidden), nn.ReLU(),
            nn.Linear(hidden, hidden),   nn.ReLU(),
        )
        self.head_nodes = nn.Linear(hidden, num_nodes)
        self.head_vel   = nn.Linear(hidden, num_velocities)

    def forward(self, x):
        h = self.shared(x)
        return self.head_nodes(h), self.head_vel(h)



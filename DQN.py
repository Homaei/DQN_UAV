# Physical UAV stub
# Simulates the real world with noise and imperfections
# ═══════════════════════════════════════════════════════════════
class PhysicalUAVStub:
    """
    Stands in for the actual UAV hardware (or a high-fidelity emulator).

    Key differences from the digital twin:
      - GPS position has Gaussian noise
      - Path-loss uses the real exponent 2.8, not the twin's initial guess of 2.0
      - Measurements include random fading and sensor noise

    This is what the twin must sync against and calibrate from.
    In real deployment, replace this class with actual hardware calls.
    """
    def __init__(self, num_nodes: int = NUM_NODES, seed: int = 7):
        self.num_nodes = num_nodes
        rng = random.Random(seed)
        np.random.seed(seed + 1)

        # sensor positions — the twin doesn't know these exactly at first
        self._node_xy = []
        for _ in range(num_nodes):
            r  = UAV_RADIUS * math.sqrt(rng.random())
            th = rng.uniform(0, 2 * math.pi)
            self._node_xy.append((r * math.cos(th), r * math.sin(th)))

        # circular flight path
        theta        = np.linspace(0, 2 * math.pi, 361)
        self._uav_x  = UAV_RADIUS * np.cos(theta)
        self._uav_y  = UAV_RADIUS * np.sin(theta)
        self._t      = 0
        self._aoi    = np.full(num_nodes, MAX_AOI, dtype=np.float32)
        self._queues = [deque() for _ in range(num_nodes)]

        # seed initial packets in queues
        for i in range(num_nodes):
            if rng.random() < PKT_ARRIVAL_P:
                for _ in range(20):
                    self._queues[i].append(1)

    def get_telemetry(self) -> dict:
        """
        Returns a noisy telemetry packet — what the UAV actually transmits to the twin.
        Both position and path-loss readings are corrupted by noise.
        """
        true_x = self._uav_x[self._t]
        true_y = self._uav_y[self._t]

        # GPS noise
        meas_x = true_x + np.random.normal(0, POSITION_NOISE_STD)
        meas_y = true_y + np.random.normal(0, POSITION_NOISE_STD)

        # path-loss with real physics plus noise
        measured_pl = []
        for i in range(self.num_nodes):
            nx, ny = self._node_xy[i]
            d = math.sqrt((true_x - nx)**2 + (true_y - ny)**2 + BASE_ALTITUDE**2)
            d = max(d, 1.0)
            # true physics: real exponent 2.8
            pl_true = (20 * math.log10(max(4 * math.pi * d / WAVELENGTH, 1e-9))
                       + TRUE_PATH_LOSS_EXP * 10 * math.log10(d))
            # add sensor noise and random channel fading
            pl_meas = (pl_true
                       + np.random.normal(0, MEASUREMENT_NOISE_STD)
                       + np.random.normal(0, CHANNEL_FADE_STD))
            measured_pl.append(pl_meas)

        return {
            "t":         self._t,
            "pos_x":     meas_x,
            "pos_y":     meas_y,
            "aoi":       self._aoi.copy(),
            "path_loss": np.array(measured_pl, dtype=np.float32),
            "node_xy":   list(self._node_xy),
        }

    def execute_action(self, node_idx: int, velocity_idx: int) -> dict:
        """Runs an action on the physical UAV and returns the resulting telemetry."""
        velocity   = VELOCITY_TABLE[velocity_idx]
        steps      = max(1, int(velocity * TIMESTEP_DUR))
        self._t    = (self._t + steps) % len(self._uav_x)

        tel = self.get_telemetry()
        pl  = tel["path_loss"]

        # serve the selected sensor
        if self._queues[node_idx]:
            self._queues[node_idx].popleft()
            if pl[node_idx] < PKT_LOSS_THRESH:
                # bad channel: reception failed, AoI gets worse
                self._aoi[node_idx] = min(self._aoi[node_idx] + 1, MAX_AOI)
            else:
                # good channel: data received, AoI resets
                self._aoi[node_idx] = 1.0
        else:
            # nothing in queue
            self._aoi[node_idx] = min(self._aoi[node_idx] + 1, MAX_AOI)

        # age AoI for all other sensors
        for i in range(self.num_nodes):
            if i == node_idx:
                continue
            if random.random() < PKT_ARRIVAL_P:
                self._queues[i].append(1)
            self._aoi[i] = min(self._aoi[i] + 1, MAX_AOI)
            while len(self._queues[i]) > MAX_QUEUE_LEN:
                self._queues[i].popleft()

        return self.get_telemetry()



NUM_NODES        = 10
BASE_ALTITUDE    = 100.0        # UAV flight altitude in metres
UAV_RADIUS       = 400.0        # radius of the circular flight path in metres
MAX_AOI          = 20.0         # AoI is capped at this value for each sensor
PKT_ARRIVAL_P    = 0.7          # probability a new packet arrives at a sensor each step
